"""M1 证据档位的**共享措辞** —— 单一事实源。

## 为什么需要这个文件（2026-09-18 第六轮审计二 P1-1）

同一个缺陷的措辞**曾在两处各改一半**：

- `utils/rag/retrieve.py` 的 `NONE_EVIDENCE_NOTE`（**工具返回值**，权威低）已从
  「请如实告知用户**知识库中没有相关内容**」改成「关联性**未能确认**」。
  理由：对 `rel-0014`（gold 在 rank 4）/ `rel-0015`（gold 在 **rank 1**）而言，
  「没有」是**关于语料内容的假断言** —— 答案明明在语料里，只是字面判据没通过。
- 而 `utils/agent_core.py` 的 `AGENT_SYSTEM_PROMPT` 第 3 条（**系统提示词，权威更高**）
  **原封未动**，仍命令模型「必须明确告诉用户"**该数据不可得**"」。

⇒ 系统提示词权威更高，模型会照它办 —— 于是那句假陈述**从高权威的位置重新出现**。
金融产品里对用户断言"没有该数据"、而该断言为假，是本项目最该避免的输出形态。

**修法**：两边都从**本模块**取措辞，物理上消灭"第三次各改一半"。
本模块**零依赖**（纯字符串常量），可被 `utils/rag/*` 与 `utils/agent_core.py` 同时导入。

## 三个常量的分工

| 常量 | 谁用 | 性质 |
|---|---|---|
| `NO_HIT_MESSAGE` | `retrieve.py` 工具返回 | **真**「零命中」时的提示 —— 此处说"没有"是**真陈述** |
| `NONE_EVIDENCE_NOTE` | `retrieve.py` 工具返回 | 判据未通过时的警示（**数据**，模型读到的） |
| `WEAK_EVIDENCE_NOTE` | `retrieve.py` 工具返回 | 弱相关档的安全网 |
| `NONE_EVIDENCE_DIRECTIVE` | `agent_core.py` 系统提示词 | 同上语义，但作为**指令**（权威更高，模型会照做） |
"""

# ── 工具返回值用（模型读到的**数据**）────────────────────────────────
# 无命中时的显式提示：把「没有」这件事说清楚，模型才不会拿训练数据硬编。
# ⚠️ 这里说"知识库中没有相关内容"是**真陈述**（确实零命中），与下面 NONE 档的语义不同。
NO_HIT_MESSAGE = "未找到相关公告或研报 —— 请如实告知用户知识库中没有相关内容，不要凭记忆编造"

# 证据不足档（A3a）：**不是无条件空结果**，而是「返回候选 + 最强警示」——
# 例外见 `hybrid.run_hybrid` 的「分层硬停」（零 bigram 交集 → 仍物理回空）。
#
# ⚠️ 2026-09-18 措辞订正（第五轮审计 A 的 P1-2）：旧文案写「请如实告知用户**知识库中没有相关内容**」——
# 该警示的语义本该是「**我的字面判据没通过**」，而不是关于语料内容的事实断言。
NONE_EVIDENCE_NOTE = ("证据判据未通过（与问题的字面重合不足）—— 以下候选的关联性**未能确认**，"
                      "引用前请自行核验；若候选不足以支撑回答，请如实说明未找到，不要据此推断或编造")

# 证据不足档（A3b 的安全网）：结果照给，但明确要求模型谨慎
WEAK_EVIDENCE_NOTE = ("检索到的内容与问题只有字面弱相关（证据不足档）—— 引用前请自行核验；"
                      "若无法支撑回答，请如实说明未找到，不要据此推断")

# ── 系统提示词用（模型读到的**指令**，权威更高）──────────────────────
# 与 `NONE_EVIDENCE_NOTE` **同源** —— 关键差异在最后一句：
#   **不得断言"知识库中没有该数据"**，因为「判据未通过」≠「语料里没有」。
NONE_EVIDENCE_DIRECTIVE = (
    '工具返回 {"error": ...}、空数据/全 None、或 `evidence_level` 为 "none"（证据判据未通过）时，'
    '必须如实说明「**未能确认该数据 / 判据未通过**」并说明原因，'
    '**不得断言"知识库中没有该数据"**（判据未通过 ≠ 语料里没有 —— 语料可能确有答案，'
    '只是与问题的字面重合不足）；绝不猜测、绝不编造数据。'
)
